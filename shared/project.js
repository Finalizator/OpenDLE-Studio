export function addRoom(project, { x, y, width, depth, color = '#597b9a' }) {
  number(x, 'Room X');
  number(y, 'Room Y');
  number(width, 'Room width', 32, 8192);
  number(depth, 'Room depth', 32, 8192);
  const vertices = [[x, y], [x + width, y], [x + width, y + depth], [x, y + depth]]
    .map(([vx, vy]) => ({ id: newId('v'), x: vx, y: vy }));
  project.map.vertices.push(...vertices);
  const sectorId = newId('sector');
  if (project.map.sectors) project.map.sectors.push({ id: sectorId, floorHeight: 0, ceilingHeight: 128, light: 208, sky: false });
  project.map.walls.push(...vertices.map((vertex, index) => ({
    id: newId('w'), a: vertex.id, b: vertices[(index + 1) % 4].id, color, height: 128, solid: true,
    ...(project.map.sectors ? { right: { sectorId, offsetX: 0, offsetY: 0 } } : {}),
  })));
}

/**
 * A blank object to take a deleted object's place, when its rules are being kept.
 *
 * Artwork and gameplay components are removed; type, local data, signals, interaction area and
 * body remain so kept rules still have valid targets. A model stays only for animation rules.
 */
export function standInFor(original, id, { keepModel = false } = {}) {
  const stand = {
    id, name: `${original?.name || 'Object'} (empty)`.slice(0, 100), type: original?.type || 'decoration',
    x: Number(original?.x) || 0, y: Number(original?.y) || 0, angle: Number(original?.angle) || 0,
  };
  if (original?.elevation) stand.elevation = original.elevation;
  if (original?.physics) stand.physics = cloneProjectData(original.physics);
  if (original?.area) stand.area = cloneProjectData(original.area);
  if (original?.variables) stand.variables = cloneProjectData(original.variables);
  if (original?.signals || original?.terminal?.submitSignal) stand.signals = nodeSignals(original);
  if (original?.health !== undefined) stand.health = original.health;
  if (keepModel && original?.modelAsset) stand.modelAsset = original.modelAsset;
  return stand;
}

export function removeEntities(project, ids, { keepReferences = false } = {}) {
  const targets = [...new Set([].concat(ids))].map(id => project.map.entities.find(entity => entity.id === id));
  assert(targets.every(entity => entity && entity.type !== 'player'), 'Select non-player entities to delete');
  if (keepReferences) {
    const mapping = new Map();
    const events = [...project.events, ...timesheetCueEvents(project.timesheets)];
    for (const entity of targets) {
      const keepModel = events.some(event => [event.condition, ...(event.conditions || []), ...event.actions].some(command =>
        ['animationFinished', 'playAnimation', 'stopAnimation'].includes(command.type) &&
        (commandTargets(command).some(target => target.id === entity.id) ||
          command.entityId === '$self' && (event.ownerId === entity.id || event.forEachType === entity.type))));
      const stand = standInFor(entity, newId('entity'), { keepModel });
      project.map.entities.push(stand);
      mapping.set(entity.id, stand.id);
    }
    rewriteEntityReferences(project, mapping);
  }
  const removing = targets.map(entity => entity.id);
  stripEntityReferences(project, removing);
  for (const id of removing) removeEntity(project, id);
}

/**
 * Deletes one object.
 *
 * It refuses while anything still names it — an event, a timeline cue, a spawn template — because
 * a project that names an object it does not have is invalid, and half the references (a cue, a
 * spawn template, an `otherId`) used to slip past this check and leave exactly that behind. The
 * editor asks first and clears the names itself (`stripEntityReferences` or
 * `rewriteEntityReferences`), so reaching here with a reference is a bug rather than a user error.
 */
export function removeEntity(project, id) {
  const entity = project.map.entities.find(item => item.id === id);
  assert(entity && entity.type !== 'player', 'Select a non-player entity to delete');
  const references = entityReferences(project, id).filter(reference => reference.ownerId !== id || !reference.owned);
  assert(!references.length,
    `This entity is used by ${references.map(reference => reference.name).slice(0, 3).join(', ')}`
    + `${references.length > 3 ? ` and ${references.length - 3} more` : ''}. Remove those references first.`);
  project.events = project.events.filter(event => event.ownerId !== id);
  // A cue owned by the object is its script too, and a cue that outlived its object targets
  // nothing — the same rule the events above follow.
  for (const sheet of project.timesheets || []) {
    sheet.cues = (sheet.cues || []).filter(cue => cue.ownerId !== id);
  }
  project.map.entities = project.map.entities.filter(item => item.id !== id);
  // A group holds objects; when its last member is gone it is not a group any more.
  if (project.map.entityGroups) {
    const used = new Set(project.map.entities.map(item => item.groupId).filter(Boolean));
    project.map.entityGroups = project.map.entityGroups.filter(group => used.has(group.id));
    for (const group of project.map.entityGroups) {
      if (group.kind === 'scene' && group.rootId === id) group.rootId = project.map.entities.find(item => item.groupId === group.id).id;
    }
  }
  // A joint cannot hold an object that is gone.
  if (project.map.joints) project.map.joints = project.map.joints.filter(joint => joint.a !== id && joint.b !== id);
}
