// Measures the animation of every classic Doom monster by asking GZDoom.
//
//   node tools/gzdoom/measure-actors.mjs
//   node tools/gzdoom/measure-actors.mjs --classes Imp, Demon
//
// For each class it runs a scenario that summons the actor into MAP01 and records the state
// table GZDoom reports, then writes `shared/vanilla-animations.js`: per class, per label,
// the frames and durations the real engine plays. `shared/actors.js` builds the classic actor
// table from it and `shared/sprite-animation.js` builds the sprite clips from it, so a plain
// WAD import animates the way Doom does instead of the way a summary guessed.
//
// The file is generated data, so it carries where it came from: the release and the IWAD.
// Regenerate it with this script after changing either.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runScenario } from './run.mjs';
import { readAnimation, clipDuration } from './animation.mjs';
import { VANILLA_ACTORS } from '/home/allukard/Code/OpenDLE/shared/actors.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const OUTPUT = join(root, 'shared/vanilla-animations.js');

/** MAP01 is used for every measurement: it has floor space and no hazard at the start. */
const SCENARIO = { iwad: 'Projects/Doom2.wad', map: 'MAP01', skill: 3, tics: 40, action: 'aim', angle: 90 };

/** Command-line classes, so one actor can be re-measured without the whole list. */
function requestedClasses(argv) {
  const at = argv.indexOf('--classes');
  if (at < 0) return VANILLA_ACTORS.map(actor => actor.name);
  return argv[at + 1].split(',').map(name => name.trim()).filter(Boolean);
}

async function measure(name) {
  const scenario = { ...SCENARIO, name: `measure-${name.toLowerCase()}`, watch: name, summon: [name] };
  const result = await runScenario(scenario);
  const animation = readAnimation(result.lines.join('\n'));
  // GZDoom names the class as it resolves it (`ZombieMan`), which is the key we keep.
  const measured = animation[name] || animation[Object.keys(animation)[0]];
  if (!measured) throw new Error(`${name}: GZDoom reported no state table\n${result.log.split('\n').slice(-8).join('\n')}`);
  return measured;
}

async function main() {
  const names = requestedClasses(process.argv.slice(2));
  const animations = {};
  const failures = [];
  for (const name of names) {
    process.stdout.write(`${name.padEnd(18)}`);
    try {
      const measured = await measure(name);
      animations[name] = measured;
      const labels = Object.keys(measured).length;
      const tics = Object.values(measured).reduce((total, frames) => total + clipDuration(frames), 0);
      console.log(`${String(labels).padStart(2)} label(s), ${String(tics).padStart(4)} tics`);
    } catch (error) {
      console.log(`failed: ${error.message.split('\n')[0]}`);
      failures.push(name);
    }
  }

  // A partial run (--classes) must not throw the rest of the file away.
  let existing = {};
  try { existing = (await import(`${OUTPUT}?t=${Date.now()}`)).VANILLA_ANIMATIONS || {}; } catch { /* first run */ }
  const merged = Object.fromEntries(Object.entries({ ...existing, ...animations }).sort(([a], [b]) => a.localeCompare(b)));
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, renderModule(merged));
  console.log(`\nwrote ${Object.keys(merged).length} class(es) to shared/vanilla-animations.js`);
  if (failures.length) {
    console.error(`failed: ${failures.join(', ')}`);
    process.exitCode = 1;
  }
}

/**
 * The generated module.
 *
 * It is JavaScript rather than JSON because both the server and the browser load
 * `shared/`, and a JSON module import still needs a flag in Node and an attribute in the
 * browser. A generated `.js` module has no loader to configure.
 *
 * `SPRITE_ANIMATIONS` is the same data keyed by sprite prefix, because the sprite clips are
 * per prefix: it is what the renderer and the entity sprite states use, while
 * `VANILLA_ANIMATIONS` is what the actor state machines use.
 */
function renderModule(classes) {
  const spriteByPrefix = {};
  for (const actor of VANILLA_ACTORS) {
    const measured = classes[actor.name];
    if (!measured || !actor.sprite) continue;
    spriteByPrefix[actor.sprite] = {
      see: sequence(measured.See), missile: sequence(measured.Missile),
      pain: sequence(measured.Pain), death: sequence(measured.Death),
    };
  }
  const body = JSON.stringify(classes, null, 2).replace(/"(\w+)":/g, '$1:');
  const sprites = JSON.stringify(spriteByPrefix, null, 2).replace(/"(\w{4})":/g, '$1:');
  return `// Generated by tools/gzdoom/measure-actors.mjs from the real engine. Do not edit.
//
// Measured with ${'GZDoom g4.14.2'} from ${SCENARIO.iwad} (${SCENARIO.map}).
// Each label lists the frames GZDoom plays, in order: the frame letter (A upwards), its
// duration in tics (35 per second, -1 for a state that holds forever) and GZDoom's sprite
// index, which is what identifies the picture when a label changes sprite.
//
// Regenerate after changing the IWAD or the GZDoom release:
//   node tools/gzdoom/measure-actors.mjs

export const VANILLA_ANIMATIONS = ${body};

/** The same measurements per sprite prefix, for the sprite clips. */
export const SPRITE_ANIMATIONS = ${sprites};
`;
}

/**
 * One label as a clip-friendly summary: its letters and the length of one frame.
 *
 * A sprite clip has one duration for all its frames (`shared/sprite-animation.js`), so a run
 * of the same letter is collapsed into one frame with the added duration — Doom's zombie
 * walks `AABBCCDD` at four tics each, which is exactly `ABCD` at eight. The picture is
 * identical and the clip stays uniform; the actor state machine keeps all eight states,
 * because those are separate states with separate actions.
 */
function sequence(frames) {
  if (!frames || !frames.length) return null;
  const runs = [];
  for (const frame of frames) {
    const last = runs.at(-1);
    if (last && last.letter === frame.letter) last.tics += Math.max(1, frame.tics);
    else runs.push({ letter: frame.letter, tics: Math.max(1, frame.tics) });
  }
  const letters = runs.map(run => run.letter).join('');
  const tics = Math.round(runs.reduce((total, run) => total + run.tics, 0) / runs.length);
  return { letters, tics, frames: frames.length };
}

await main();
